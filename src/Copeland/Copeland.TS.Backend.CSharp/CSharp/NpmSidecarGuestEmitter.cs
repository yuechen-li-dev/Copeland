using System.Text;
using System.Text.Encodings.Web;
using Copeland.TS.Mir;

namespace Copeland.TS.Backend.CSharp;

internal static class NpmSidecarGuestEmitter
{
    internal static string Operation(MirNpmCallExpression call)
        => $"npm:{call.PackageName}@{call.PackageVersion}:{call.ExportName}";

    internal static string? Emit(
        MirProgram program,
        CSharpSidecarContract? contract,
        IReadOnlyList<MirNpmCallExpression> calls,
        List<CSharpDiagnostic> diagnostics)
    {
        if (contract is null || contract.RunTarget.Runtime != "node" || contract.RunTarget.Command.Count != 1)
        {
            diagnostics.Add(new("COPE-CS-NPM-GUEST-0001", "A generated npm guest requires a default Node sidecar with one script path."));
            return null;
        }

        var plans = program.TsonEncodingPlans.ToDictionary(plan => plan.Id);
        var source = new StringBuilder("// <auto-generated />\n");
        source.Append("const protocol = ").Append(Quote(contract.ProtocolVersion)).AppendLine(";");
        source.Append("const digest = ").Append(Quote(contract.ExpectedDigest)).AppendLine(";");
        source.AppendLine("const operations = new Map([");

        foreach (var group in calls.GroupBy(Operation).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            if (group.Any(call => !Supports(plans[call.RequestPlanId])
                || !Supports(plans[call.ResponsePlanId])
                || !Supports(plans[call.RemoteErrorPlanId])))
            {
                diagnostics.Add(new("COPE-CS-NPM-GUEST-0003", $"npm operation '{group.Key}' needs a DTO shape the generated guest cannot encode."));
                continue;
            }

            var declarations = group.Select(call => OperationEntry(call, plans)).Distinct(StringComparer.Ordinal).ToArray();
            if (declarations.Length != 1)
            {
                diagnostics.Add(new("COPE-CS-NPM-GUEST-0002", $"npm operation '{group.Key}' has conflicting TSON contracts."));
                continue;
            }

            source.Append("    ").Append(declarations[0]).AppendLine(",");
        }
        source.AppendLine("]);");
        if (diagnostics.Count > 0)
        {
            return null;
        }

        using Stream runtime = typeof(NpmSidecarGuestEmitter).Assembly.GetManifestResourceStream("Copeland.NpmSidecarGuest.mjs")
            ?? throw new InvalidOperationException("The compiler is missing its npm guest runtime.");
        using var reader = new StreamReader(runtime);
        return source.Append(reader.ReadToEnd()).ToString().ReplaceLineEndings("\n");
    }

    private static string OperationEntry(MirNpmCallExpression call, IReadOnlyDictionary<MirTsonEncodingPlanId, MirTsonEncodingPlan> plans)
        => $"[{Quote(Operation(call))}, {{ packageName: {Quote(call.PackageName)}, exportName: {Quote(call.ExportName)}, "
            + $"request: {Document(plans[call.RequestPlanId])}, response: {Document(plans[call.ResponsePlanId])}, "
            + $"error: {Document(plans[call.RemoteErrorPlanId])} }}]";

    private static string Document(MirTsonEncodingPlan plan)
    {
        var records = plan.Definitions.OfType<MirTsonRecordPlan>().ToDictionary(record => record.RecordTypeId);
        return $"{{ prefix: {Quote(MirTsonCanonicalText.BuildDocumentPrefix(plan))}, shape: {Shape(plan.RootValuePlan, records)}, "
            + $"maxBytes: {plan.Limits.MaximumUtf8Bytes}, maxString: {plan.Limits.MaximumStringCodeUnits}, maxArray: {plan.Limits.MaximumArrayLength} }}";
    }

    private static bool Supports(MirTsonEncodingPlan plan)
        => plan.TablePlan is null && plan.Definitions.All(definition => definition is MirTsonRecordPlan);

    private static string Shape(MirTsonValuePlan plan, IReadOnlyDictionary<MirRecordTypeId, MirTsonRecordPlan> records)
        => plan switch
        {
            MirTsonBooleanPlan => "\"boolean\"",
            MirTsonNumberPlan => "\"number\"",
            MirTsonStringPlan => "\"string\"",
            MirTsonArrayPlan array => $"[\"array\", {Shape(array.ElementPlan, records)}]",
            MirTsonRecordValuePlan record => RecordShape(records[record.RecordTypeId], records),
            _ => throw new InvalidOperationException("Unsupported value in a validated npm transport plan."),
        };

    private static string RecordShape(MirTsonRecordPlan record, IReadOnlyDictionary<MirRecordTypeId, MirTsonRecordPlan> records)
    {
        IEnumerable<string> fields = record.Fields.Select(field => $"[{Quote(field.Name)}, {Shape(field.ValuePlan, records)}]");
        return $"[\"record\", {Quote(record.Name)}, [{string.Join(", ", fields)}]]";
    }

    private static string Quote(string value) => "\"" + JavaScriptEncoder.Default.Encode(value) + "\"";
}
