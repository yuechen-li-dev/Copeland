    private static void EmitNugetOperation(
        CSharpTextWriter writer, NugetOperation operation,
        IReadOnlyDictionary<MirTsonEncodingPlanId, MirTsonEncodingPlan> plans,
        IReadOnlyDictionary<MirRecordTypeId, MirRecordDefinition> records, NugetDtoProjection projection, int index)
    {
        MirTsonEncodingPlan request = plans[operation.Request];
        MirTsonRecordPlan requestRecord = WorkerRecord(request);
        MirTsonRecordPlan response = WorkerRecord(plans[operation.Response]);
        MirTsonRecordPlan error = WorkerRecord(plans[operation.Error]);
        if (response.Fields.Count != 1 || error.Fields.Count != 1 || error.Fields[0].ValuePlan is not MirTsonStringPlan)
        {
            throw new InvalidDataException($"NuGet worker operation '{operation.Binding.Operation}' needs a one-field result and a one-string-field error.");
        }
        string requestPrefix = MirTsonCanonicalText.BuildDocumentPrefix(request);
        MirType result = records[response.RecordTypeId].Fields[0].Type;
        string responseType = MapType(result);
        string invocation = projection.Invoke(operation.Binding, records[requestRecord.RecordTypeId], result);
        writer.WriteLine($"private static (string Kind, string Payload) Operation{index}(string payload)");
        writer.WriteLine("{");
        writer.Indent();
        if (requestRecord.Fields.Count == 0)
        {
            string empty = requestPrefix + "$record." + requestRecord.Name + "({});\n";
            writer.WriteLine($"if (payload != {CSharpLiteralWriter.Write(empty)}) return (\"failure\", \"\");");
        }
        else
        {
            writer.WriteLine($"if (!payload.StartsWith({CSharpLiteralWriter.Write(requestPrefix)}, global::System.StringComparison.Ordinal)) return (\"failure\", \"\");");
            writer.WriteLine($"var request = {TsonDecodeMethodName(operation.Request)}(payload);");
        }
        writer.WriteLine($"{responseType} value;");
        writer.WriteLine("try");
        writer.WriteLine("{");
        writer.Indent();
        writer.WriteLine($"value = {invocation};");
        writer.Unindent();
        writer.WriteLine("}");
        writer.WriteLine("catch (global::System.Exception error)");
        writer.WriteLine("{");
        writer.Indent();
        writer.WriteLine($"return Encode(\"remote-error\", {TsonEncodeMethodName(operation.Error)}(new {RecordTypeName(error.RecordTypeId)}(error.Message)));");
        writer.Unindent();
        writer.WriteLine("}");
        writer.WriteLine($"return Encode(\"ok\", {TsonEncodeMethodName(operation.Response)}(new {RecordTypeName(response.RecordTypeId)}(value)));");
        writer.Unindent();
        writer.WriteLine("}");
    }

    private sealed record NugetOperation(
        NugetWorkerBinding Binding, MirTsonEncodingPlanId Request, MirTsonEncodingPlanId Response, MirTsonEncodingPlanId Error);
}
