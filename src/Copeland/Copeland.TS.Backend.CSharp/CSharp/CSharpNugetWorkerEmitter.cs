using System.Security.Cryptography;
using System.Text;
using Copeland.TS.Mir;

namespace Copeland.TS.Backend.CSharp;

public sealed record NugetWorkerBinding(string Operation, string Type, string Method)
{
    public bool ProjectDto { get; init; }
    public IReadOnlyList<string> TypeArguments { get; init; } = [];
    public IReadOnlySet<int> ObjectParameters { get; init; } = new HashSet<int>();
    public string? RequestRecordName { get; init; }
}

public sealed record CSharpNugetWorker(string Source, string Digest);

public static partial class CSharpBackend
{
    public const string NugetWorkerProtocol = "copeland-nuget-worker-v1";
    public const string GeneratedNugetSchema = "copeland://interop/nuget/generated/v1";

    /// <summary>Builds a CLR worker from the exact DTO plans used by the generated Node calls.</summary>
    public static CSharpNugetWorker EmitNugetWorker(
        MirProgram program,
        IReadOnlyList<MirTsonTransportExpression> calls,
        IReadOnlyList<NugetWorkerBinding> bindings,
        string configurationFingerprint,
        bool useStdio = true,
        IReadOnlySet<MirRecordTypeId>? dtoRecords = null)
    {
        var byOperation = bindings.ToDictionary(binding => binding.Operation, StringComparer.Ordinal);
        var plans = program.TsonEncodingPlans.ToDictionary(plan => plan.Id);
        var selectedPlans = new Dictionary<MirTsonEncodingPlanId, MirTsonEncodingPlan>();
        var operations = new SortedDictionary<string, NugetOperation>(StringComparer.Ordinal);
        foreach (MirTsonTransportExpression call in calls)
        {
            if (call.Operation is not MirLiteralExpression { Value: string name })
            {
                throw new InvalidDataException("A generated NuGet worker requires a literal tsonCall operation name.");
            }
            if (!byOperation.TryGetValue(name, out NugetWorkerBinding? binding))
            {
                throw new InvalidDataException($"NuGet worker operation '{name}' is not declared.");
            }

            var operation = new NugetOperation(binding, call.RequestPlanId, call.ResponsePlanId, call.RemoteErrorPlanId);
            if (operations.TryGetValue(name, out NugetOperation? previous) && previous != operation)
            {
                throw new InvalidDataException($"NuGet worker operation '{name}' has conflicting DTO plans.");
            }
            operations[name] = operation;
            foreach (MirTsonEncodingPlanId id in new[] { operation.Request, operation.Response, operation.Error })
            {
                selectedPlans.TryAdd(id, plans[id]);
            }
        }
        foreach (NugetWorkerBinding binding in bindings)
        {
            if (!operations.ContainsKey(binding.Operation))
            {
                throw new InvalidDataException($"NuGet worker operation '{binding.Operation}' has no matching tsonCall.");
            }
        }

        var records = program.Records.ToDictionary(record => record.Id);
        foreach (MirTsonEncodingPlan plan in selectedPlans.Values)
        {
            if (plan.TablePlan is not null || plan.RootValuePlan is not MirTsonRecordValuePlan)
            {
                throw new InvalidDataException($"NuGet worker DTO '{plan.RootType.Identifier}' must be a TSON record.");
            }
        }

        MirTsonEncodingPlan[] orderedPlans = selectedPlans.Values.OrderBy(plan => plan.Id.Value, StringComparer.Ordinal).ToArray();
        var writer = new CSharpTextWriter();
        writer.WriteLine("// <auto-generated />");
        writer.WriteLine("#nullable enable");
        writer.WriteLine("namespace Copeland.Generated;");
        writer.WriteLine();
        EmitResult(writer);
        EmitEnum(writer, program.Enums.Single(definition => definition.Name == "TsonEncodeError"));
        var enums = program.Enums.ToDictionary(definition => definition.Name, StringComparer.Ordinal);
        var projection = new NugetDtoProjection(records, enums, dtoRecords);
        foreach (MirRecordTypeId id in orderedPlans.SelectMany(plan => plan.Definitions)
            .OfType<MirTsonRecordPlan>().Select(record => record.RecordTypeId).Concat(projection.RecordIds).Distinct())
        {
            EmitRecord(writer, records[id], usesSystemTextJson: false);
        }
        foreach (string name in orderedPlans.SelectMany(plan => plan.Definitions)
            .OfType<MirTsonEnumPlan>().Select(definition => definition.Name).Concat(projection.OptionNames())
            .Distinct(StringComparer.Ordinal).Where(name => name != "TsonEncodeError"))
        {
            EmitEnum(writer, enums[name]);
        }
        projection.Emit(writer);

        string digest = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(
            configurationFingerprint + "\n" + string.Join("\n", orderedPlans.Select(MirTsonCanonicalText.BuildDocumentPrefix)))));
        writer.WriteLine("internal static class NugetWorker");
        writer.WriteLine("{");
        writer.Indent();
        EmitTsonEncodingRuntime(writer, orderedPlans, records, emitTransportDecoders: true);
        writer.WriteLine($"private const string Protocol = {CSharpLiteralWriter.Write(NugetWorkerProtocol)};");
        writer.WriteLine($"private const string Digest = {CSharpLiteralWriter.Write(digest)};");
        if (useStdio)
        {
            EmitNugetWorkerLoop(writer);
        }
        else
        {
            EmitNugetBrowserEndpoint(writer);
        }
        EmitNugetDispatch(writer, operations.Values);
        int index = 0;
        foreach (NugetOperation operation in operations.Values)
        {
            EmitNugetOperation(writer, operation, selectedPlans, records, projection, index++);
        }
        writer.Unindent();
        writer.WriteLine("}");
        return new CSharpNugetWorker(writer.ToString(), digest);
    }

    private static MirTsonRecordPlan WorkerRecord(MirTsonEncodingPlan plan)
    {
        var root = (MirTsonRecordValuePlan)plan.RootValuePlan;
        return plan.Definitions.OfType<MirTsonRecordPlan>().Single(record => record.RecordTypeId == root.RecordTypeId);
    }

    private static void EmitNugetWorkerLoop(CSharpTextWriter writer)
    {
        writer.WriteLine("""
            private static int Main()
            {
                var utf8 = new global::System.Text.UTF8Encoding(false, true);
                global::System.Console.InputEncoding = utf8;
                global::System.Console.OutputEncoding = utf8;
                var output = global::System.Console.Out;
                global::System.Console.SetOut(global::System.Console.Error);
                string? hello = global::System.Console.ReadLine();
                if (!Read(hello, out string correlation, out string kind, out string operation, out string payload)
                    || correlation != "" || kind != "handshake" || operation != Protocol || payload != Digest)
                {
                    return 2;
                }
                output.WriteLine(global::Copeland.TS.Sidecar.SidecarWire.Write("", "handshake", Protocol, Digest));
                output.Flush();
                while (global::System.Console.ReadLine() is string line)
                {
                    if (!Read(line, out correlation, out kind, out operation, out payload)
                        || correlation.Length == 0 || kind != "request")
                    {
                        return 2;
                    }
                    var reply = Dispatch(operation, payload);
                    string frame = global::Copeland.TS.Sidecar.SidecarWire.Write(correlation, reply.Kind, "", reply.Payload);
                    if (utf8.GetByteCount(frame) > global::Copeland.TS.Sidecar.SidecarWire.MaximumFrameBytes)
                    {
                        frame = global::Copeland.TS.Sidecar.SidecarWire.Write(correlation, "failure", "", "");
                    }
                    output.WriteLine(frame);
                    output.Flush();
                }
                return 0;
            }
            """);
    }

    private static void EmitNugetBrowserEndpoint(CSharpTextWriter writer)
    {
        writer.WriteLine("""
            internal static string? Invoke(string digest, string frame)
            {
                if (digest != Digest || !Read(frame, out string correlation, out string kind, out string operation, out string payload)
                    || correlation.Length == 0 || kind != "request")
                {
                    return null;
                }
                var reply = Dispatch(operation, payload);
                string response = global::Copeland.TS.Sidecar.SidecarWire.Write(correlation, reply.Kind, "", reply.Payload);
                if (global::System.Text.Encoding.UTF8.GetByteCount(response) > global::Copeland.TS.Sidecar.SidecarWire.MaximumFrameBytes)
                {
                    return null;
                }
                return response;
            }
            """);
    }

    private static void EmitNugetDispatch(CSharpTextWriter writer, IEnumerable<NugetOperation> operations)
    {
        writer.WriteLine("""
