using System.Diagnostics;
using System.Text;
using System.Text.Json;
using System.Xml.Linq;
using Copeland.TS.Backend.CSharp;
using Copeland.TS.Compiler;

namespace Copeland.Cli;

internal static partial class TsclBuildContract
{
    private const string GeneratedNugetModule = "src/generated/Nuget.ts";
    private const string GeneratedNugetHeader = "// Generated by tscl nuget generate.\n";

    public static int RunNuget(string[] args)
    {
        if (args.Length != 3 || args[1] != "generate")
        {
            Console.Error.WriteLine("COPE-TSCL-NUGET-0005 error: Usage: tscl nuget generate <project-root>.");
            return UsageErrorExitCode;
        }
        try
        {
            string projectRoot = Path.GetFullPath(args[2]);
            if (ReadNugetWorker(projectRoot) is not { Signatures.Count: > 0 } config)
            {
                throw new TsclContractException("COPE-TSCL-NUGET-0005", "Binding generation requires nuget-worker.json schemaVersion 2 or 3.");
            }
            CopelandProjectSource source = GenerateNugetBindings(projectRoot, config);
            string? existing = File.Exists(source.SourcePath)
                ? File.ReadAllText(source.SourcePath).ReplaceLineEndings("\n")
                : null;
            if (existing is not null && !existing.StartsWith(GeneratedNugetHeader, StringComparison.Ordinal))
            {
                throw new TsclContractException("COPE-TSCL-NUGET-0005", $"Move the existing '{GeneratedNugetModule}' before generating bindings.");
            }
            if (existing != source.SourceText)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(source.SourcePath)!);
                string temporaryPath = source.SourcePath + "." + Guid.NewGuid().ToString("N") + ".tmp";
                try
                {
                    File.WriteAllText(temporaryPath, source.SourceText);
                    File.Move(temporaryPath, source.SourcePath, overwrite: true);
                }
                finally
                {
                    File.Delete(temporaryPath);
                }
            }
            Console.WriteLine(source.SourcePath);
            return 0;
        }
        catch (TsclContractException error)
        {
            Console.Error.WriteLine($"{error.Code} error: {error.Message}");
            return CompileFailureExitCode;
        }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException)
        {
            Console.Error.WriteLine($"COPE-TSCL-NUGET-0005 error: {error.Message}");
            return FileIoErrorExitCode;
        }
    }

    private static CopelandProjectSource GenerateNugetBindings(
        string projectRoot, NugetWorkerConfiguration config)
    {
        string directory = Path.Combine(projectRoot, ".tscl-nuget-signatures-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory);
        try
        {
            WriteStagedFile(directory, "Signatures.csproj", new XElement("Project",
                new XAttribute("Sdk", "Microsoft.NET.Sdk"),
                new XElement("PropertyGroup",
                    new XElement("TargetFramework", "net10.0"),
                    new XElement("ManagePackageVersionsCentrally", "false")),
                NugetPackageReferences(config.Packages)).ToString());
            var start = new ProcessStartInfo("dotnet")
            {
                WorkingDirectory = directory,
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                CreateNoWindow = true,
            };
            start.ArgumentList.Add("restore");
            start.ArgumentList.Add("Signatures.csproj");
            using Process process = Process.Start(start)!;
            Task<string> output = process.StandardOutput.ReadToEndAsync();
            Task<string> errors = process.StandardError.ReadToEndAsync();
            process.WaitForExit();
            if (process.ExitCode != 0)
            {
                throw new InvalidDataException($"NuGet signature restore failed.\n{output.Result}\n{errors.Result}");
            }

            using JsonDocument assets = JsonDocument.Parse(File.ReadAllText(Path.Combine(directory, "obj", "project.assets.json")));
            var metadata = new NugetPackageSignatures(assets.RootElement);
            var source = new StringBuilder(GeneratedNugetHeader);
            source.AppendLine($"const $schema: string = \"{CSharpBackend.GeneratedNugetSchema}\";");
            source.AppendLine("export record NugetError { message: string; }");
            foreach ((string name, IReadOnlyDictionary<string, string> fields) in config.Records)
            {
                source.AppendLine().AppendLine($"export record {name} {{");
                foreach ((string fieldName, string fieldType) in fields)
                {
                    source.AppendLine($"    {fieldName}: {fieldType};");
                }
                source.AppendLine("}");
            }
            foreach (NugetSignature signature in config.Signatures)
            {
                NugetWireSignature wire = metadata.Resolve(signature);
                AppendNugetBinding(source, signature, wire);
            }
            return new(GeneratedNugetModule, Path.Combine(projectRoot, GeneratedNugetModule), source.ToString().ReplaceLineEndings("\n"));
        }
        catch (Exception error) when (error is InvalidDataException or IOException or JsonException
            or BadImageFormatException or System.ComponentModel.Win32Exception or KeyNotFoundException)
        {
            throw new TsclContractException("COPE-TSCL-NUGET-0005", error.Message);
        }
        finally
        {
            Directory.Delete(directory, recursive: true);
        }
    }

    private static void AppendNugetBinding(StringBuilder source, NugetSignature signature, NugetWireSignature wire)
    {
        // Use positional names for wire stability across package versions.
        string request = signature.Export + "Request";
        string reply = signature.Export + "Reply";
        string fields = string.Join(" ", wire.Parameters.Select((type, index) => $"arg{index}: {type};"));
        string arguments = string.Join(", ", wire.Parameters.Select((type, index) => $"arg{index}: {type}"));
        string values = string.Join(", ", wire.Parameters.Select((_, index) => $"arg{index}: arg{index}"));
        source.AppendLine($$"""

            record {{request}} { {{fields}} }
            record {{reply}} { value: {{wire.Result}}; }

            export async function {{signature.Export}}({{arguments}}): {{wire.Result}} ! NugetError {
                const request: {{request}} = { {{values}} };
                const pending: Async<{{reply}} ! NugetError> = tsonCall<{{reply}}, NugetError>("{{signature.Binding.Operation}}", request);
                const reply: {{reply}} ! NugetError = await pending;
                return match reply {
                    ok(value) => ok(value.value),
                    err(error) => err(error),
                };
            }
            """);
    }

}
